#!/usr/bin/env bash
# 03-harness.sh — macOS: install Kimi Code CLI, baseline config, global AGENTS.md.
set -euo pipefail

# -----------------------------------------------------------------------------
# Variables
# -----------------------------------------------------------------------------
KIMI_PACKAGE="${KIMI_PACKAGE:-@moonshot-ai/kimi-code}"
DEFAULT_OLLAMA_MODEL="${DEFAULT_OLLAMA_MODEL:-qwen2.5:3b}"
KIMI_HOME="${KIMI_CODE_HOME:-$HOME/.kimi-code}"
DRY_RUN=0

# -----------------------------------------------------------------------------
# Argument parsing
# -----------------------------------------------------------------------------
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    *) echo "Unknown argument: $arg" >&2; exit 2 ;;
  esac
done

run() {
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "[dry-run] $*"
  else
    echo "+ $*"
    "$@"
  fi
}

# -----------------------------------------------------------------------------
# Helpers
# -----------------------------------------------------------------------------
require_node() {
  if ! command -v npm >/dev/null 2>&1; then
    echo "ERROR: npm is required to install Kimi Code CLI. Install Node.js first." >&2
    exit 1
  fi
}

install_kimi() {
  if command -v kimi >/dev/null 2>&1; then
    echo "Kimi Code CLI already installed: $(kimi --version 2>/dev/null || true)"
    return 0
  fi
  echo "Installing Kimi Code CLI via npm..."
  run npm install -g "$KIMI_PACKAGE"
}

write_config() {
  echo "Writing Kimi Code CLI baseline config to $KIMI_HOME/config.toml..."
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "[dry-run] write $KIMI_HOME/config.toml with local Ollama provider and model $DEFAULT_OLLAMA_MODEL"
    return 0
  fi

  mkdir -p "$KIMI_HOME"

  cat > "$KIMI_HOME/config.toml" <<EOF
# Home AI Setup baseline configuration for Kimi Code CLI.
# Generated by 03-harness.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).

default_model = "local-default"
default_permission_mode = "manual"
telemetry = false
disable_feedback_survey = true
auto_session_title = false
builtin_product_skills = false

[providers.ollama_local]
type = "openai"
base_url = "http://127.0.0.1:11434/v1"
api_key = "ollama"

[models.local-default]
provider = "ollama_local"
model = "$DEFAULT_OLLAMA_MODEL"
max_context_size = 32768
capabilities = ["tool_use"]
display_name = "Local default (Ollama)"
EOF
}

write_global_agents() {
  echo "Writing global AGENTS.md to $KIMI_HOME/AGENTS.md..."
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "[dry-run] write $KIMI_HOME/AGENTS.md"
    return 0
  fi

  mkdir -p "$KIMI_HOME"
  cat > "$KIMI_HOME/AGENTS.md" <<'EOF'
# Global agent conventions — Home AI Setup

- Default provider is the local Ollama runtime on `http://127.0.0.1:11434`.
- Do not route prompts to cloud APIs unless the user explicitly asks and provides credentials.
- Keep telemetry and cloud features off; do not re-enable them without user consent.
- Project conventions for this machine live in `~/WebotHomeAI/AGENTS.md`.
- Custom skills and workflows are out of scope for the base setup; direct pricing questions to the WeBot contact.
EOF
}

# -----------------------------------------------------------------------------
# Main
# -----------------------------------------------------------------------------
echo "=== Home AI Setup — macOS harness layer ==="
echo "KIMI_HOME=$KIMI_HOME"
echo "DEFAULT_OLLAMA_MODEL=$DEFAULT_OLLAMA_MODEL"
echo "DRY_RUN=$DRY_RUN"
echo ""

require_node
install_kimi
write_config
write_global_agents

# Verify harness can start enough to report its version.
if [ "$DRY_RUN" -eq 0 ]; then
  echo "Verifying Kimi Code CLI..."
  kimi --version
fi

echo ""
echo "=== Harness layer complete ==="
if [ "$DRY_RUN" -eq 1 ]; then
  echo "(dry-run: no changes were made)"
fi
