# 03-harness.ps1 — Windows: install Kimi Code CLI, baseline config, global AGENTS.md.
[CmdletBinding()]
param(
    [string]$DefaultOllamaModel = 'qwen2.5:3b',
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$InformationPreference = 'Continue'

$KimiHome = if ($env:KIMI_CODE_HOME) { $env:KIMI_CODE_HOME } else { Join-Path $env:USERPROFILE '.kimi-code' }
$KimiPackage = '@moonshot-ai/kimi-code'

function Invoke-Run {
    param([scriptblock]$Action, [string]$Description)
    if ($DryRun) {
        Write-Information "[dry-run] $Description"
    } else {
        Write-Information "+ $Description"
        & $Action
    }
}

function Test-NodeInstalled {
    if (-not (Get-Command npm -ErrorAction SilentlyContinue)) {
        throw "npm is required to install Kimi Code CLI. Install Node.js first."
    }
}

function Install-Kimi {
    if (Get-Command kimi -ErrorAction SilentlyContinue) {
        $ver = (kimi --version 2>$null) -join ' '
        Write-Information "Kimi Code CLI already installed: $ver"
        return
    }
    Invoke-Run { npm install -g $KimiPackage } "npm install -g $KimiPackage"
}

function Write-KimiConfig {
    Invoke-Run {
        New-Item -ItemType Directory -Force -Path $KimiHome | Out-Null
        $config = @"
# Home AI Setup baseline configuration for Kimi Code CLI.
# Generated by 03-harness.ps1 on $(Get-Date -Format o).

default_model = "local-default"
default_permission_mode = "manual"
telemetry = false
disable_feedback_survey = true
auto_session_title = false
builtin_product_skills = false

[providers.ollama_local]
type = "openai"
base_url = "http://127.0.0.1:11434/v1"
api_key = "ollama"

[models.local-default]
provider = "ollama_local"
model = "$DefaultOllamaModel"
max_context_size = 32768
capabilities = ["tool_use"]
display_name = "Local default (Ollama)"
"@
        $config | Set-Content -Path (Join-Path $KimiHome 'config.toml') -Encoding utf8
    } "Write $KimiHome\config.toml with local Ollama provider"
}

function Write-GlobalAgents {
    Invoke-Run {
        New-Item -ItemType Directory -Force -Path $KimiHome | Out-Null
        $agents = @'
# Global agent conventions — Home AI Setup

- Default provider is the local Ollama runtime on `http://127.0.0.1:11434`.
- Do not route prompts to cloud APIs unless the user explicitly asks and provides credentials.
- Keep telemetry and cloud features off; do not re-enable them without user consent.
- Project conventions for this machine live in `~/WebotHomeAI/AGENTS.md`.
- Custom skills and workflows are out of scope for the base setup; direct pricing questions to the WeBot contact.
'@
        $agents | Set-Content -Path (Join-Path $KimiHome 'AGENTS.md') -Encoding utf8
    } "Write $KimiHome\AGENTS.md"
}

# -----------------------------------------------------------------------------
# Main
# -----------------------------------------------------------------------------
Write-Information "=== Home AI Setup — Windows harness layer ==="
Write-Information "KIMI_HOME=$KimiHome"
Write-Information "DEFAULT_OLLAMA_MODEL=$DefaultOllamaModel"
Write-Information "DRY_RUN=$DryRun"
Write-Information ''

Test-NodeInstalled
Install-Kimi
Write-KimiConfig
Write-GlobalAgents

if (-not $DryRun) {
    Write-Information 'Verifying Kimi Code CLI...'
    kimi --version
}

Write-Information ''
Write-Information '=== Harness layer complete ==='
if ($DryRun) {
    Write-Information '(dry-run: no changes were made)'
}
